import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";

import type { Bot, Context } from "grammy";
import type { BotCommand, Message, Sticker } from "grammy/types";

import { bot as botInstance } from "@/lib/bot";
import { logger } from "@/lib/logger";

const OUTPUT_PATH = resolve(process.cwd(), "src/lib", "icons.ts");
const RELATIVE_OUTPUT_PATH = relative(process.cwd(), OUTPUT_PATH).replaceAll(
	"\\",
	"/",
);

interface IconCandidate {
	customEmojiId: string;
	fallback: string;
	entity: { offset: number; length: number } | null;
}

export interface IconDetail {
	key: string;
	customEmojiId: string;
	fallback: string;
	entity: { offset: number; length: number } | null;
	sticker: {
		fileId: string;
		fileUniqueId: string;
		emoji: string | null;
		setName: string | null;
		stickerType: string;
		width: number;
		height: number;
		isAnimated: boolean;
		isVideo: boolean;
		format: "static" | "animated" | "video";
	} | null;
	receivedMessage: {
		messageId: number;
		chatId: string;
		isForwarded: boolean;
		forwardOriginType: string | null;
	};
	capturedAt: string;
}

const BOT_COMMANDS: BotCommand[] = [
	{ command: "start", description: "Start the icon collector bot" },
	{ command: "icon_details", description: "Save custom emoji as a unique key" },
	{ command: "grab", description: "Shortcut for /icon_details" },
	{ command: "overwrite", description: "Replace an existing icon key" },
	{ command: "list", description: "List all saved icons in icons.ts" },
	{ command: "remove", description: "Delete an icon key from icons.ts" },
	{ command: "help", description: "Show usage instructions" },
];

function getForwardMetadata(message: Message): {
	isForwarded: boolean;
	forwardOriginType: string | null;
} {
	const forwardedMessage = message as Message & {
		forward_origin?: { type?: string };
		forward_from?: unknown;
		forward_from_chat?: unknown;
		forward_sender_name?: string;
	};

	const isForwarded = Boolean(
		forwardedMessage.forward_origin ||
			forwardedMessage.forward_from ||
			forwardedMessage.forward_from_chat ||
			forwardedMessage.forward_sender_name,
	);

	return {
		isForwarded,
		forwardOriginType:
			forwardedMessage.forward_origin?.type ?? (isForwarded ? "legacy" : null),
	};
}

function extractCandidates(message: Message): IconCandidate[] {
	const text = message.text ?? message.caption ?? "";
	const entities =
		message.text !== undefined
			? (message.entities ?? [])
			: (message.caption_entities ?? []);
	const candidatesById = new Map<string, IconCandidate>();

	for (const entity of entities) {
		if (entity.type !== "custom_emoji") continue;

		const fallback =
			text.slice(entity.offset, entity.offset + entity.length) || "✨";

		if (!candidatesById.has(entity.custom_emoji_id)) {
			candidatesById.set(entity.custom_emoji_id, {
				customEmojiId: entity.custom_emoji_id,
				fallback,
				entity: { offset: entity.offset, length: entity.length },
			});
		}
	}

	// Support a standalone custom-emoji sticker message
	const stickerEmojiId = message.sticker?.custom_emoji_id;
	if (stickerEmojiId && !candidatesById.has(stickerEmojiId)) {
		candidatesById.set(stickerEmojiId, {
			customEmojiId: stickerEmojiId,
			fallback: message.sticker?.emoji || "✨",
			entity: null,
		});
	}

	return [...candidatesById.values()];
}

function loadExistingRegistry(): Record<string, IconDetail> {
	if (!existsSync(OUTPUT_PATH)) return {};

	const source = readFileSync(OUTPUT_PATH, "utf8");
	// Supports both the new ICON_REGISTRY name and legacy CONED_ICON_DETAILS
	const match = source.match(
		/export const (?:ICON_REGISTRY|CONED_ICON_DETAILS) = (\{[\s\S]*?\}) as const satisfies Record<string, (?:IconDetail|ConedIconDetail)>;/,
	);

	if (!match?.[1]) {
		throw new Error(
			`Cannot read ${RELATIVE_OUTPUT_PATH}. It exists but does not match the expected auto-generated format. Back it up before replacing it.`,
		);
	}

	return JSON.parse(match[1]) as Record<string, IconDetail>;
}
function writeRegistry(registry: Record<string, IconDetail>): void {
	mkdirSync(dirname(OUTPUT_PATH), { recursive: true });

	const sortedRegistry = Object.fromEntries(
		Object.entries(registry).sort(([keyA], [keyB]) => keyA.localeCompare(keyB)),
	);

	const fileContents = `// AUTO-GENERATED by scripts/icon-cloner.ts. Do not edit manually.
// Use customEmojiId across your bots. sticker.fileId is specific to the bot that fetched it.

import type { InlineKeyboardButton } from "grammy/types";

export interface IconDetail {
	key: string;
	customEmojiId: string;
	fallback: string;
	entity: { offset: number; length: number } | null;
	sticker: {
		fileId: string;
		fileUniqueId: string;
		emoji: string | null;
		setName: string | null;
		stickerType: string;
		width: number;
		height: number;
		isAnimated: boolean;
		isVideo: boolean;
		format: "static" | "animated" | "video";
	} | null;
	receivedMessage: {
		messageId: number;
		chatId: string;
		isForwarded: boolean;
		forwardOriginType: string | null;
	};
	capturedAt: string;
}

export const ICON_REGISTRY = ${JSON.stringify(sortedRegistry, null, "\t")} as const satisfies Record<string, IconDetail>;

export type IconName = keyof typeof ICON_REGISTRY;

/**
 * Renders a saved Telegram custom emoji as an HTML <tg-emoji> tag.
 */
export function renderIcon(name: IconName): string {
	const icon = ICON_REGISTRY[name];
	return \`<tg-emoji emoji-id="\${icon.customEmojiId}">\${icon.fallback}</tg-emoji>\`;
}

export function iconInlineButton(
	iconName: IconName,
	text: string,
	data = "noop",
): InlineKeyboardButton.CallbackButton {
	return {
		text,
		callback_data: data,
		icon_custom_emoji_id: ICON_REGISTRY[iconName].customEmojiId,
	};
}
`;

	writeFileSync(OUTPUT_PATH, fileContents, "utf8");
}

function escapeHtml(value: string): string {
	return value
		.replaceAll("&", "&amp;")
		.replaceAll("<", "&lt;")
		.replaceAll(">", "&gt;")
		.replaceAll('"', "&quot;");
}

function getNextAvailableKey(
	baseKey: string,
	registry: Record<string, IconDetail>,
	startIndex: number,
): { key: string; nextIndex: number } {
	let index = startIndex;
	while (true) {
		const candidateKey = index === 1 ? baseKey : `${baseKey}_${index}`;
		index++;
		if (!registry[candidateKey]) {
			return { key: candidateKey, nextIndex: index };
		}
	}
}

async function fetchStickerMetadataBatch(
	ctx: Context,
	emojiIds: string[],
): Promise<{ stickersById: Map<string, Sticker>; failed: boolean }> {
	const stickersById = new Map<string, Sticker>();
	let failed = false;

	// Telegram allows at most 200 custom_emoji_ids per getCustomEmojiStickers call
	for (let i = 0; i < emojiIds.length; i += 200) {
		const chunk = emojiIds.slice(i, i + 200);
		try {
			const fetched = await ctx.api.getCustomEmojiStickers(chunk);
			for (const sticker of fetched) {
				if (sticker.custom_emoji_id) {
					stickersById.set(sticker.custom_emoji_id, sticker);
				}
			}
		} catch (_error) {
			failed = true;
			logger.warn(
				"[IconCloner]",
				"Could not fetch sticker metadata chunk; saving custom emoji IDs anyway:",
			);
		}
	}

	return { stickersById, failed };
}

async function configureBotMenu(bot: Bot): Promise<void> {
	await bot.api.setMyCommands(BOT_COMMANDS);
	await bot.api.setMyCommands(BOT_COMMANDS, {
		scope: { type: "all_private_chats" },
	});
	await bot.api.setMyCommands(BOT_COMMANDS);
	await bot.api.setChatMenuButton({
		menu_button: { type: "commands" },
	});
}

async function main(): Promise<void> {
	const bot = botInstance;

	bot.command("start", async (ctx) => {
		await ctx.reply(
			[
				"<b>Icon Collector is online.</b>",
				"",
				"1. Forward a message with custom emojis to this chat.",
				"2. Reply to it with <code>/icon_details rocket</code> (or <code>/grab rocket</code>).",
				"",
				"<b>Menu Commands:</b>",
				"• <code>/icon_details &lt;key&gt;</code> — Save new icon(s) (blocks duplicates)",
				"• <code>/grab &lt;key&gt;</code> — Alias for /icon_details",
				"• <code>/overwrite &lt;key&gt;</code> — Replace an existing icon key",
				"• <code>/list</code> — View all saved icons",
				"• <code>/remove &lt;key&gt;</code> — Delete an icon key",
				"",
				`Output file: <code>${escapeHtml(RELATIVE_OUTPUT_PATH)}</code>`,
			].join("\n"),
			{ parse_mode: "HTML" },
		);
	});

	bot.command("help", async (ctx) => {
		await ctx.reply(
			[
				"<b>How to collect icons without duplicates:</b>",
				"",
				"• Reply to a message containing a custom emoji with <code>/grab rocket</code>.",
				"• Duplicate icon names and duplicate custom emoji IDs are automatically prevented.",
				"• If you intentionally want to update an existing icon name, reply with <code>/overwrite rocket</code>.",
			].join("\n"),
			{ parse_mode: "HTML" },
		);
	});

	bot.command("list", async (ctx) => {
		const registry = loadExistingRegistry();
		const entries = Object.values(registry);

		if (entries.length === 0) {
			await ctx.reply(
				`No icons saved in <code>${escapeHtml(RELATIVE_OUTPUT_PATH)}</code> yet.`,
				{ parse_mode: "HTML" },
			);
			return;
		}

		const lines = [
			`<b>Saved Icons (${entries.length}) in <code>${escapeHtml(RELATIVE_OUTPUT_PATH)}</code>:</b>`,
			"",
			...entries
				.slice(0, 50)
				.map(
					(entry) =>
						`• <code>${escapeHtml(entry.key)}</code> <tg-emoji emoji-id="${entry.customEmojiId}">${escapeHtml(entry.fallback)}</tg-emoji> (<code>${entry.customEmojiId}</code>)`,
				),
		];

		if (entries.length > 50) {
			lines.push("", `<i>...and ${entries.length - 50} more.</i>`);
		}

		await ctx.reply(lines.join("\n"), { parse_mode: "HTML" });
	});

	bot.command("remove", async (ctx) => {
		const keyToRemove = ctx.match?.trim().toLowerCase() ?? "";
		if (!keyToRemove) {
			await ctx.reply("Usage: <code>/remove &lt;key&gt;</code>", {
				parse_mode: "HTML",
			});
			return;
		}

		const registry = loadExistingRegistry();
		if (!registry[keyToRemove]) {
			await ctx.reply(
				`Icon key <code>${escapeHtml(keyToRemove)}</code> does not exist.`,
				{
					parse_mode: "HTML",
				},
			);
			return;
		}

		delete registry[keyToRemove];
		writeRegistry(registry);

		await ctx.reply(
			`Removed <code>${escapeHtml(keyToRemove)}</code> from <code>${escapeHtml(RELATIVE_OUTPUT_PATH)}</code>.`,
			{ parse_mode: "HTML" },
		);
	});

	const handleCollect = async (
		ctx: Context,
		allowOverwrite: boolean,
	): Promise<void> => {
		if (ctx.chat?.type !== "private") {
			await ctx.reply(
				"Please use this collector in a private chat with the bot.",
			);
			return;
		}

		const rawKey =
			(typeof ctx.match === "string" ? ctx.match : "").trim().split(/\s+/)[0] ??
			"";
		const baseKey = rawKey.toLowerCase();

		if (!/^[a-z][a-z0-9_]{0,47}$/.test(baseKey)) {
			const cmd = allowOverwrite ? "overwrite" : "icon_details";
			await ctx.reply(
				`Usage: reply to a message with <code>/${cmd} &lt;key&gt;</code>\nExample: <code>/${cmd} rocket</code>\n<i>(Use lowercase letters, numbers, and underscores, starting with a letter.)</i>`,
				{ parse_mode: "HTML" },
			);
			return;
		}

		const commandMessage = ctx.message;
		if (!commandMessage) return;

		const target = commandMessage.reply_to_message ?? commandMessage;
		const candidates = extractCandidates(target);

		if (candidates.length === 0) {
			await ctx.reply(
				"No Telegram custom emoji was found. Reply to a message containing a custom emoji (or a custom-emoji sticker) and try again.",
			);
			return;
		}

		const registry = loadExistingRegistry();

		// 1. Block duplicate icon names when not in /overwrite mode
		if (!allowOverwrite && candidates.length === 1 && registry[baseKey]) {
			const existing = registry[baseKey];
			await ctx.reply(
				[
					`⚠️ <b>Duplicate Icon Name Prevented</b>`,
					"",
					`The key <code>${escapeHtml(baseKey)}</code> already exists (<tg-emoji emoji-id="${existing.customEmojiId}">${escapeHtml(existing.fallback)}</tg-emoji> <code>${existing.customEmojiId}</code>).`,
					"",
					`• Choose a different name, or`,
					`• Reply with <code>/overwrite ${escapeHtml(baseKey)}</code> to replace it.`,
				].join("\n"),
				{ parse_mode: "HTML" },
			);
			return;
		}

		// Build a lookup map of existing customEmojiId -> key to prevent duplicate icons under different names
		const existingKeyByEmojiId = new Map<string, string>();
		for (const [k, detail] of Object.entries(registry)) {
			existingKeyByEmojiId.set(detail.customEmojiId, k);
		}

		const { stickersById, failed: metadataLookupFailed } =
			await fetchStickerMetadataBatch(
				ctx,
				candidates.map((c) => c.customEmojiId),
			);

		const forwardMetadata = getForwardMetadata(target);
		const savedEntries: IconDetail[] = [];
		const skippedDuplicates: Array<{
			customEmojiId: string;
			existingKey: string;
			fallback: string;
		}> = [];

		let nextIndex = 1;

		for (const candidate of candidates) {
			const alreadySavedKey = existingKeyByEmojiId.get(candidate.customEmojiId);

			// 2. Skip emojis whose customEmojiId is already saved (unless overwriting that exact key)
			if (alreadySavedKey && (!allowOverwrite || alreadySavedKey !== baseKey)) {
				skippedDuplicates.push({
					customEmojiId: candidate.customEmojiId,
					existingKey: alreadySavedKey,
					fallback: candidate.fallback,
				});
				continue;
			}

			let assignedKey: string;
			if (allowOverwrite && candidates.length === 1) {
				assignedKey = baseKey;
			} else {
				const available = getNextAvailableKey(baseKey, registry, nextIndex);
				assignedKey = available.key;
				nextIndex = available.nextIndex;
			}

			const sticker = stickersById.get(candidate.customEmojiId);
			const fallback = candidate.fallback || sticker?.emoji || "✨";

			const detail: IconDetail = {
				key: assignedKey,
				customEmojiId: candidate.customEmojiId,
				fallback,
				entity: candidate.entity,
				sticker: sticker
					? {
							fileId: sticker.file_id,
							fileUniqueId: sticker.file_unique_id,
							emoji: sticker.emoji ?? null,
							setName: sticker.set_name ?? null,
							stickerType: sticker.type,
							width: sticker.width,
							height: sticker.height,
							isAnimated: Boolean(sticker.is_animated),
							isVideo: Boolean(sticker.is_video),
							format: sticker.is_video
								? "video"
								: sticker.is_animated
									? "animated"
									: "static",
						}
					: null,
				receivedMessage: {
					messageId: target.message_id,
					chatId: String(target.chat.id),
					isForwarded: forwardMetadata.isForwarded,
					forwardOriginType: forwardMetadata.forwardOriginType,
				},
				capturedAt: new Date().toISOString(),
			};

			registry[assignedKey] = detail;
			existingKeyByEmojiId.set(candidate.customEmojiId, assignedKey);
			savedEntries.push(detail);
		}

		if (savedEntries.length > 0) {
			writeRegistry(registry);
			logger.info(
				"[IconCloner]",
				`Saved ${savedEntries.length} icon(s) to ${RELATIVE_OUTPUT_PATH}`,
			);
		}

		const responseLines: string[] = [];

		if (savedEntries.length > 0) {
			responseLines.push(
				`<b>Saved ${savedEntries.length} custom emoji(s)</b>`,
				"",
				...savedEntries
					.slice(0, 15)
					.flatMap((entry) => [
						`• <code>${escapeHtml(entry.key)}</code> <tg-emoji emoji-id="${entry.customEmojiId}">${escapeHtml(entry.fallback)}</tg-emoji>`,
						`  ID: <code>${entry.customEmojiId}</code>`,
						`  Format: <code>${escapeHtml(entry.sticker?.format ?? "metadata unavailable")}</code>`,
					]),
				"",
				`Saved to <code>${escapeHtml(RELATIVE_OUTPUT_PATH)}</code>`,
			);

			if (savedEntries.length > 15) {
				responseLines.push(
					`<i>Showing first 15 of ${savedEntries.length} saved entries.</i>`,
				);
			}
		}

		if (skippedDuplicates.length > 0) {
			if (responseLines.length > 0) responseLines.push("");
			responseLines.push(
				`<b>Skipped ${skippedDuplicates.length} already-saved emoji(s):</b>`,
				...skippedDuplicates
					.slice(0, 10)
					.map(
						(dup) =>
							`• <tg-emoji emoji-id="${dup.customEmojiId}">${escapeHtml(dup.fallback)}</tg-emoji> already exists as <code>${escapeHtml(dup.existingKey)}</code>`,
					),
			);
		}

		if (metadataLookupFailed) {
			responseLines.push(
				"",
				"<i>Note: Sticker metadata lookup failed, but custom emoji IDs were saved.</i>",
			);
		}

		await ctx.reply(responseLines.join("\n"), { parse_mode: "HTML" });
	};

	bot.command(["icon_details", "grab"], (ctx) => handleCollect(ctx, false));
	bot.command("overwrite", (ctx) => handleCollect(ctx, true));

	bot.catch(({ ctx, error }) => {
		logger.error(
			"[IconCloner]",
			`Update ${ctx.update.update_id} failed:`,
			error,
		);
	});

	await configureBotMenu(bot);

	logger.info("[IconCloner]", "Starting Telegram polling...");
	logger.info("[IconCloner]", `Output file: ${RELATIVE_OUTPUT_PATH}`);

	await bot.start({
		onStart: (me) => {
			logger.info(
				"[IconCloner]",
				`Running as @${me.username ?? me.first_name}`,
			);
		},
	});
}

main().catch((error: unknown) => {
	logger.error(
		"[IconCloner]",
		"Failed to start:",
		error instanceof Error ? error.message : error,
	);
	process.exitCode = 1;
});
